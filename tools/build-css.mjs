// Writes css/sessions.css (the session colour classes) from js/theme.js, so the page needs no inline <style>
// and the CSP can forbid inline styles. A unit test fails if the file drifts from theme.js.
//   node tools/build-css.mjs      (npm run css)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sessionCSS } from '../js/theme.js';

const out = fileURLToPath(new URL('../css/sessions.css', import.meta.url));
writeFileSync(out, `/* Generated by tools/build-css.mjs from js/theme.js. Don't edit by hand. */\n${sessionCSS()}\n`);
console.log(`Wrote ${out}`);
